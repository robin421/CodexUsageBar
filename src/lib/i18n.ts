export type Key = keyof Dict;
const dicts: Record<Lang, Dict> = { zh, en };

export const lang = writable<Lang>("zh");

export function translate(l: Lang, key: Key, params: Record<string, string | number> = {}): string {
  return dicts[l][key].replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ""));
}

export const t = derived(lang, (l) => (key: Key, params?: Record<string, string | number>) => translate(l, key, params));
